    from public.profiles p
    where p.id = p_user_id
      and (p.role = 'admin' or lower(p.email) = 'eliebakala@gmail.com')
  );
$$;

create or replace function public.is_verified_recruiter(p_user_id uuid default auth.uid())
returns boolean
language sql
stable
