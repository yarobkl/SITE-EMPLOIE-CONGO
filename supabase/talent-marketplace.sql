create or replace function public.set_profile_completion_state()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.profile_completed := (
    coalesce(nullif(trim(new.phone), ''), '') <> ''
    and coalesce(nullif(trim(new.city), ''), '') <> ''
    and (new.location_id is not null or coalesce(nullif(trim(new.other_quarter_name), ''), '') <> '')
  );
  if new.profile_completed and new.profile_completed_at is null then
    new.profile_completed_at := now();
  elsif not new.profile_completed then
    new.profile_completed_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_completion_state on public.profiles;
create trigger profiles_completion_state
before insert or update of phone, city, location_id, other_quarter_name
on public.profiles
for each row execute function public.set_profile_completion_state();

create or replace function public.complete_nzela_profile(
  p_phone text,
  p_city text,
  p_location_id bigint,
  p_other_quarter_name text,
  p_role text
)
returns public.profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.profiles;
begin
  if auth.uid() is null then
    raise exception 'AUTH_REQUIRED';
  end if;
  if coalesce(trim(p_phone), '') = '' then
    raise exception 'PHONE_REQUIRED';
  end if;
  if coalesce(trim(p_city), '') = '' then
    raise exception 'CITY_REQUIRED';
  end if;
  if p_location_id is null and coalesce(trim(p_other_quarter_name), '') = '' then
    raise exception 'QUARTER_REQUIRED';
  end if;
  if p_role not in ('candidat', 'recruteur') then
    raise exception 'INVALID_ROLE';
  end if;

  update public.profiles
  set phone = trim(p_phone),
      city = trim(p_city),
      location_id = p_location_id,
      other_quarter_name = nullif(trim(p_other_quarter_name), ''),
      role = case when role = 'admin' then role else p_role end,
      updated_at = now()
  where id = auth.uid()
  returning * into v_profile;

  return v_profile;
end;
$$;

create or replace function public.enforce_job_seeker_post_frequency()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.status = 'active' then
    if exists (
      select 1
      from public.job_seeker_posts p
      where p.candidate_id = new.candidate_id
        and p.id <> coalesce(new.id, gen_random_uuid())
        and p.published_at > now() - interval '30 days'
    ) then
      raise exception 'ONE_POST_EVERY_30_DAYS';
    end if;
    new.published_at := coalesce(new.published_at, now());
    new.expires_at := new.published_at + interval '30 days';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists job_seeker_posts_frequency on public.job_seeker_posts;
create trigger job_seeker_posts_frequency
before insert on public.job_seeker_posts
for each row execute function public.enforce_job_seeker_post_frequency();

create or replace function public.expire_job_seeker_posts()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  update public.job_seeker_posts
  set status = 'expired', archived_at = coalesce(archived_at, now()), updated_at = now()
  where status = 'active' and expires_at <= now();
  get diagnostics v_count = row_count;

  delete from public.job_matches jm
  using public.job_seeker_posts p
  where p.id = jm.job_seeker_post_id
    and (p.status <> 'active' or p.expires_at <= now());

  return v_count;
end;
$$;

create or replace function public.publish_job_seeker_post(
  p_desired_job_title text,
  p_sector text,
  p_description text,
  p_city text,
  p_location_id bigint,
  p_other_quarter_name text,
  p_contract_types text[],
  p_skills text[],
  p_experience_years integer,
  p_education_level text,
  p_availability text,
  p_mobility text,
  p_salary_min numeric,
  p_salary_max numeric,
  p_contact_visibility text default 'request'
)
returns public.job_seeker_posts
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.profiles;
  v_post public.job_seeker_posts;
begin
  perform public.expire_job_seeker_posts();

  select * into v_profile from public.profiles where id = auth.uid();
  if v_profile.id is null then raise exception 'AUTH_REQUIRED'; end if;
  if v_profile.role <> 'candidat' then raise exception 'CANDIDATE_ONLY'; end if;
  if not v_profile.profile_completed then raise exception 'PROFILE_INCOMPLETE'; end if;
  if coalesce(trim(p_desired_job_title), '') = '' then raise exception 'JOB_TITLE_REQUIRED'; end if;
  if coalesce(trim(p_description), '') = '' then raise exception 'DESCRIPTION_REQUIRED'; end if;
  if p_location_id is null and coalesce(trim(p_other_quarter_name), '') = '' then raise exception 'QUARTER_REQUIRED'; end if;

  insert into public.job_seeker_posts (
    candidate_id, desired_job_title, sector, description, city, location_id,
    other_quarter_name, contract_types, skills, experience_years, education_level,
    availability, mobility, salary_min, salary_max, contact_visibility
  ) values (
    auth.uid(), trim(p_desired_job_title), nullif(trim(p_sector), ''), trim(p_description),
    coalesce(nullif(trim(p_city), ''), v_profile.city, 'Brazzaville'), p_location_id,
    nullif(trim(p_other_quarter_name), ''), coalesce(p_contract_types, '{}'),
    coalesce(p_skills, '{}'), greatest(coalesce(p_experience_years, 0), 0),
    nullif(trim(p_education_level), ''), nullif(trim(p_availability), ''),
    nullif(trim(p_mobility), ''), p_salary_min, p_salary_max,
    case when p_contact_visibility = 'direct' then 'direct' else 'request' end
  ) returning * into v_post;

  insert into public.candidate_profiles (
