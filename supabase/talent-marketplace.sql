create table if not exists public.job_seeker_posts (
  id uuid primary key default gen_random_uuid(),
  candidate_id uuid not null references public.profiles(id) on delete cascade,
  desired_job_title text not null,
  sector text,
  description text not null,
  city text not null default 'Brazzaville',
  location_id bigint references public.locations(id) on delete set null,
  other_quarter_name text,
  contract_types text[] not null default '{}',
  skills text[] not null default '{}',
  experience_years integer not null default 0 check (experience_years >= 0 and experience_years <= 60),
  education_level text,
  availability text,
  mobility text,
  salary_min numeric,
  salary_max numeric,
  contact_visibility text not null default 'request' check (contact_visibility in ('request', 'direct')),
  status text not null default 'active' check (status in ('draft', 'active', 'expired', 'archived', 'hired', 'suspended')),
  published_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days'),
  archived_at timestamptz,
  hired_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (salary_min is null or salary_max is null or salary_max >= salary_min)
);

