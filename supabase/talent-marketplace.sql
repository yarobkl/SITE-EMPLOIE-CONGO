create or replace function public.admin_talent_market_balance()
returns table (
  job_family text,
  active_demands bigint,
  active_offers bigint,
  demand_per_offer numeric
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_nzela_admin(auth.uid()) then raise exception 'ADMIN_REQUIRED'; end if;
  return query
  with demands as (
    select lower(trim(desired_job_title)) family, count(*)::bigint amount
    from public.job_seeker_posts
    where status = 'active' and expires_at > now()
    group by lower(trim(desired_job_title))
  ), offers as (
    select lower(trim(title)) family, count(*)::bigint amount
    from public.jobs
    where status = 'published'
    group by lower(trim(title))
  )
  select
    coalesce(d.family, o.family),
    coalesce(d.amount, 0),
    coalesce(o.amount, 0),
    case when coalesce(o.amount, 0) = 0 then null
         else round(coalesce(d.amount, 0)::numeric / o.amount::numeric, 2)
    end
  from demands d
  full join offers o on o.family = d.family
  order by coalesce(d.amount, 0) desc, coalesce(o.amount, 0) desc
  limit 100;
end;
$$;

