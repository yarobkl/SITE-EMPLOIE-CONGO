create or replace function public.calculate_job_match_score(p_job_id uuid, p_post_id uuid)
returns table (
  title_score numeric,
  skills_score numeric,
  experience_score numeric,
  location_score numeric,
  contract_score numeric,
  availability_score numeric,
  education_score numeric,
  total_score numeric
)
language sql
stable
security definer
set search_path = public
as $$
with j as (
  select * from public.jobs where id = p_job_id
), p as (
  select * from public.job_seeker_posts where id = p_post_id
), scored as (
  select
    case
      when lower(trim(j.title)) = lower(trim(p.desired_job_title)) then 30
      when lower(j.title) like '%' || lower(p.desired_job_title) || '%'
        or lower(p.desired_job_title) like '%' || lower(j.title) || '%' then 24
      when lower(concat_ws(' ', j.title, j.sector, j.description))
        like '%' || lower(split_part(p.desired_job_title, ' ', 1)) || '%' then 16
      else 0
    end::numeric as title_score,
    least(25, coalesce((
      select count(*) * 5
      from unnest(p.skills) candidate_skill
      where lower(concat_ws(' ', j.title, j.sector, j.description, array_to_string(j.requirements, ' '), array_to_string(j.skills, ' ')))
        like '%' || lower(candidate_skill) || '%'
    ), 0))::numeric as skills_score,
    case
      when j.experience_min_years is null then 15
      when p.experience_years >= j.experience_min_years then 15
      when j.experience_min_years = 0 then 15
      else round((p.experience_years::numeric / j.experience_min_years::numeric) * 15, 2)
    end::numeric as experience_score,
    case
      when j.location_id is not null and j.location_id = p.location_id then 10
      when lower(coalesce(j.location, '')) = lower(coalesce(p.city, '')) then 8
      when lower(coalesce(j.location, '')) like '%' || lower(coalesce(p.city, '')) || '%' then 7
      else 0
    end::numeric as location_score,
    case
      when coalesce(cardinality(p.contract_types), 0) = 0 then 5
      when exists (select 1 from unnest(p.contract_types) ct where lower(ct) = lower(j.contract_type)) then 10
      else 0
    end::numeric as contract_score,
    case
      when j.availability_required is null then 5
      when lower(coalesce(p.availability, '')) = lower(j.availability_required) then 5
      else 2
    end::numeric as availability_score,
    case
      when j.education_level is null then 5
      when lower(coalesce(p.education_level, '')) = lower(j.education_level) then 5
      else 2
    end::numeric as education_score
  from j cross join p
)
select
  title_score,
  skills_score,
  experience_score,
  location_score,
  contract_score,
  availability_score,
  education_score,
  least(100, title_score + skills_score + experience_score + location_score + contract_score + availability_score + education_score)::numeric as total_score
from scored;
$$;

create or replace function public.rebuild_job_matches(p_job_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  perform public.expire_job_seeker_posts();
  delete from public.job_matches where job_id = p_job_id;

  insert into public.job_matches (
    job_id, job_seeker_post_id, candidate_id, score, title_score, skills_score,
    experience_score, location_score, contract_score, availability_score,
    education_score, generated_at
  )
  select
    p_job_id, p.id, p.candidate_id, s.total_score, s.title_score, s.skills_score,
    s.experience_score, s.location_score, s.contract_score, s.availability_score,
    s.education_score, now()
  from public.job_seeker_posts p
  cross join lateral public.calculate_job_match_score(p_job_id, p.id) s
  where p.status = 'active' and p.expires_at > now()
  order by s.total_score desc, p.published_at desc
  limit 100;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

